#!/usr/bin/env bash
# Segment reuse evaluation runner for vLLM-HUST.
#
# Runs three experimental conditions on the same model + hardware:
#   1. Baseline: E||B order + prefix cache (standard vLLM)
#   2. Reorder: B||E order + prefix cache (prompts reordered)
#   3. Stitch: E||B order + segment reuse (VLLM_SEGMENT_REUSE=stitch)
#
# Usage:
#   ./run_segment_reuse_eval.sh \
#     --model <model_path> \
#     --api-url http://localhost:8000 \
#     --workload workload_segment_reuse.jsonl \
#     --results-dir results/
#
# Prerequisites:
#   - vLLM server running with --enable-prefix-caching
#   - Workload generated by benchmark_segment_reuse.py

set -euo pipefail

# --- Defaults ---
MODEL=""
API_URL="http://localhost:8000/v1/completions"
WORKLOAD=""
RESULTS_DIR="results/segment_reuse_eval"
NUM_PROMPTS=72
REQUEST_RATE=2.0  # requests per second
MAX_CONCURRENCY=16
OUTPUT_LEN=50

# --- Parse args ---
while [[ $# -gt 0 ]]; do
    case "$1" in
        --model) MODEL="$2"; shift 2;;
        --api-url) API_URL="$2"; shift 2;;
        --workload) WORKLOAD="$2"; shift 2;;
        --results-dir) RESULTS_DIR="$2"; shift 2;;
        --request-rate) REQUEST_RATE="$2"; shift 2;;
        --max-concurrency) MAX_CONCURRENCY="$2"; shift 2;;
        --num-prompts) NUM_PROMPTS="$2"; shift 2;;
        *) echo "Unknown arg: $1"; exit 1;;
    esac
done

if [[ -z "$MODEL" ]]; then
    echo "ERROR: --model is required"
    exit 1
fi
if [[ -z "$WORKLOAD" ]]; then
    echo "ERROR: --workload is required"
    exit 1
fi

# --- Setup ---
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
mkdir -p "$RESULTS_DIR"

TIMESTAMP=$(date +%Y%m%d_%H%M%S)
echo "=== Segment Reuse Evaluation ==="
echo "Model: $MODEL"
echo "API: $API_URL"
echo "Workload: $WORKLOAD"
echo "Results: $RESULTS_DIR"
echo "Timestamp: $TIMESTAMP"
echo ""

# --- Step 1: Generate workload if not provided ---
if [[ ! -f "$WORKLOAD" ]]; then
    echo "Generating workload..."
    python "$SCRIPT_DIR/benchmark_segment_reuse.py" -o "$WORKLOAD"
fi

# --- Step 2: Generate reordered workload ---
REORDERED_WORKLOAD="${WORKLOAD%.jsonl}.reordered.jsonl"
echo "Generating reordered workload..."
python "$SCRIPT_DIR/reorder_requests.py" -i "$WORKLOAD" -o "$REORDERED_WORKLOAD"

# --- Helper function ---
run_benchmark() {
    local name="$1"
    local dataset="$2"
    local segment_reuse="$3"
    local output_file="$RESULTS_DIR/${name}_${TIMESTAMP}.json"

    echo ""
    echo "=== Running: $name ==="
    echo "  Dataset: $dataset"
    echo "  VLLM_SEGMENT_REUSE: $segment_reuse"
    echo "  Output: $output_file"

    VLLM_SEGMENT_REUSE="$segment_reuse" \
    python -m vllm.benchmarks.benchmark_serving \
        --backend vllm \
        --model "$MODEL" \
        --dataset-name custom \
        --dataset-path "$dataset" \
        --num-prompts "$NUM_PROMPTS" \
        --request-rate "$REQUEST_RATE" \
        --max-concurrency "$MAX_CONCURRENCY" \
        --save-result \
        --result-filename "$output_file" \
        2>&1 | tee "$RESULTS_DIR/${name}_${TIMESTAMP}.log"

    echo "  Done: $name"
}

# --- Step 3: Run all three conditions ---

# Condition 1: Baseline (E||B + prefix cache)
run_benchmark "baseline" "$WORKLOAD" "off"

# Condition 2: Reorder (B||E + prefix cache)
run_benchmark "reorder" "$REORDERED_WORKLOAD" "off"

# Condition 3: Stitch (E||B + segment reuse)
run_benchmark "stitch" "$WORKLOAD" "stitch"

# --- Step 4: Analyze results ---
echo ""
echo "=== Analyzing Results ==="
python "$SCRIPT_DIR/segment_reuse_analysis.py" \
    --results-dir "$RESULTS_DIR" \
    --timestamp "$TIMESTAMP" \
    --output "$RESULTS_DIR/comparison_${TIMESTAMP}.json"

echo ""
echo "=== Evaluation Complete ==="
echo "Results in: $RESULTS_DIR/"
ls -la "$RESULTS_DIR/"*"$TIMESTAMP"*
